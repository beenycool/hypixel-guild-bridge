const InsertBatchSize = 500

const MigrationColumns: Partial<Record<string, readonly string[]>> = {
  AllMembers: ['id', 'uuid', 'fromTimestamp', 'toTimestamp'],
  OnlineMembers: ['id', 'uuid', 'fromTimestamp', 'toTimestamp']
}

async function migrateFromSqlite(application: Application, sqliteManager: SqliteManager): Promise<void> {
  const sqlitePath = application.getConfigFilePath('users.sqlite')
  if (!fs.existsSync(sqlitePath)) return

  const Database = (await import('better-sqlite3')).default
  const sqliteDb = new Database(sqlitePath, { readonly: true })

  try {
    const tables: Array<{ name: string }> = sqliteDb
      .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name != 'sqlite_sequence'")
      .all() as Array<{ name: string }>
    const tableNames = new Set(tables.map((t) => t.name))

    for (const table of MigrationTableOrder) {
      if (!tableNames.has(table)) continue

      const rows = normalizeRowsForMigration(
        table,
        sqliteDb.prepare(`SELECT * FROM "${table}"`).all() as Record<string, unknown>[]
      )
      if (rows.length === 0) continue

      const columns = getMigrationColumns(table, rows[0])
      if (columns.length === 0) continue

      console.log(`Migrating ${rows.length} rows from SQLite table "${table}"`)

      await sqliteManager.transaction(async (database) => {
        for (const batch of chunkRows(rows, InsertBatchSize)) {
          await insertBatch(database, table, columns, batch)
        }

        if (SequenceTables.includes(table)) {
          const maxIdRow = sqliteDb.prepare(`SELECT MAX(id) as maxId FROM "${table}"`).get() as { maxId: number | null }
          if (maxIdRow.maxId != null) {
            await database.query(`SELECT setval(pg_get_serial_sequence('"${table}"', 'id'), $1)`, [maxIdRow.maxId])
          }
        }
      })
    }

    await sqliteManager.execute(
      'DELETE FROM "proxies" WHERE "id" NOT IN (SELECT "proxyId" FROM "mojangInstances" WHERE "proxyId" IS NOT NULL)'
    )

    sqliteDb.close()

    const backupPath = `${sqlitePath}.migrated-${Date.now()}`
    fs.renameSync(sqlitePath, backupPath)
    console.log(`SQLite migration complete. Old database backed up to: ${backupPath}`)
  } catch (error) {
    sqliteDb.close()
    throw new Error(`Failed to migrate SQLite data to PostgreSQL: ${error}`)
  }
}

function normalizeRowsForMigration(table: string, rows: Record<string, unknown>[]): Record<string, unknown>[] {
  if (table === 'mojangInstances') {
    return dedupeRows(rows, (row) => String(row.name).toLowerCase())
  }

  if (table === 'mojangSessions') {
    return dedupeRows(rows, (row) => `${String(row.name).toLowerCase()}:${String(row.cacheName)}`)
  }

  return rows
}

function dedupeRows(
  rows: Record<string, unknown>[],
  getKey: (row: Record<string, unknown>) => string
): Record<string, unknown>[] {
  const deduped = new Map<string, Record<string, unknown>>()
  for (const row of rows) {
    deduped.set(getKey(row), row)
  }

  return [...deduped.values()]
}

function getMigrationColumns(table: string, row: Record<string, unknown>): string[] {
  const allowedColumns = MigrationColumns[table]
  if (allowedColumns === undefined) return Object.keys(row)
  return allowedColumns.filter((column) => column in row)
}

async function insertBatch(
  database: { query(text: string, values?: readonly unknown[]): Promise<unknown> },
  table: string,
  columns: readonly string[],
  rows: Record<string, unknown>[]
): Promise<void> {
  const valuePlaceholders: string[] = []
  const values: unknown[] = []

  for (const row of rows) {
    const placeholderGroup: string[] = []
    for (const column of columns) {
      values.push(row[column])
      placeholderGroup.push(`$${values.length}`)
    }

    valuePlaceholders.push(`(${placeholderGroup.join(', ')})`)
  }

  await database.query(
    `INSERT INTO "${table}" (${columns.map((column) => `"${column}"`).join(', ')}) VALUES ${valuePlaceholders.join(', ')} ON CONFLICT DO NOTHING`,
    values
  )
}

function chunkRows<T>(rows: T[], size: number): T[][] {
  const chunks: T[][] = []
  for (let index = 0; index < rows.length; index += size) {
    chunks.push(rows.slice(index, index + size))
  }

  return chunks
}
