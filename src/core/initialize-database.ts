export async function initializeCoreDatabase(
  application: Application,
  sqliteManager: SqliteManager,
  _name: string
): Promise<void> {
  await sqliteManager.awaitReady()

  for (const statement of SchemaStatements) {
    await sqliteManager.execute(statement)
  }

  await migrateFromSqlite(application, sqliteManager)
}

